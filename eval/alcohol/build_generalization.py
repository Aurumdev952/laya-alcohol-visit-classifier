def main():
    assert len(TRIPLETS) == 30
    rows = []
    for group_no, (scenario, shared, direct, indirect, negative) in enumerate(TRIPLETS, 1):
        for label, evidence in (("direct", direct), ("indirect", indirect), ("negative", negative)):
            case_id = f"gen-{group_no:02d}-{label}"
            rows.append({
                "case_id": case_id,
                "patient_id": case_id,
                "group_id": f"g{group_no:02d}",
                "label": label,
                "source": "authored_counterfactual",
                "scenario": scenario,
                "encounters": [
                    {"type": "presentation", "note": shared},
                    {"type": "clinician assessment", "note": evidence},
                ],
            })
    output = Path("eval/alcohol/generalization.jsonl")
    write_jsonl(output, rows)
    print(f"wrote {len(rows)} cases in {len(TRIPLETS)} counterfactual groups to {output}")


if __name__ == "__main__":
    main()
